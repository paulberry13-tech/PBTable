create or replace function public.admin_comp_booking(p_session_kind text, p_session_id uuid, p_member_id uuid)
returns jsonb
language plpgsql security definer
set search_path to 'public'
as $function$
declare
  v_club uuid; v_capacity int; v_booked int; v_booking_id uuid;
  v_target_club uuid; v_target_uid uuid;
  v_existing bookings; v_pos int;   -- migration 97
begin
  -- Resolve + lock the session, get its club and capacity.
  if p_session_kind = 'social' then
    select club_id, capacity into v_club, v_capacity from social_sessions where id = p_session_id for update;
  elsif p_session_kind = 'graded' then
    select club_id, capacity into v_club, v_capacity from session_plans where id = p_session_id for update;
  else raise exception 'bad_session_kind'; end if;
  if v_club is null then raise exception 'session_not_found'; end if;

  -- The CALLER must be a club admin of this club.
  if not private.is_club_admin(v_club) then raise exception 'not_admin'; end if;
  perform private.require_admin_perm(v_club, 'booking.comp');   -- migration 71

  -- The TARGET must be a member of this club AND themselves a club admin (comp = admin perk).
  select club_id, auth_user_id into v_target_club, v_target_uid from booking_members where id = p_member_id;
  if v_target_club is null then raise exception 'member_not_found'; end if;
  if v_target_club <> v_club then raise exception 'wrong_club'; end if;
  if v_target_uid is null or not exists (
    select 1 from club_admins where user_id = v_target_uid and club_id = v_club
  ) then raise exception 'target_not_admin'; end if;

  -- No double-booking. migration 97: someone already WAITING (and paying when promoted) can be
  -- made a comp; someone booked, or already a comp in the queue, cannot be comped twice.
  select * into v_existing from bookings
   where session_kind = p_session_kind and session_id = p_session_id
     and member_id = p_member_id and status in ('booked', 'waitlisted')
   limit 1;
  if v_existing.id is not null and (v_existing.status <> 'waitlisted' or v_existing.comp) then
    raise exception 'already_booked';
  end if;

  -- Respect capacity — a comp occupies a real spot; never oversell.
  select count(*) into v_booked from bookings
    where session_kind = p_session_kind and session_id = p_session_id and status in ('booked', 'attended');

  if v_capacity is null or v_booked < v_capacity then
    -- A free place: the £0 comp booking — NO ledger entry, so wallets/balances are untouched.
    if v_existing.id is not null then
      -- migration 97: they were waiting; they leave the queue for the place. Waiting cost nothing.
      update bookings set status = 'booked', waitlist_pos = null, price_charged_pennies = 0,
             taster = false, comp = true, comped_by = auth.uid()
       where id = v_existing.id and status = 'waitlisted'
      returning id into v_booking_id;
      if v_booking_id is null then raise exception 'already_booked'; end if;
    else
      insert into bookings(club_id, session_kind, session_id, member_id, price_charged_pennies, status, comp, comped_by)
        values (v_club, p_session_kind, p_session_id, p_member_id, 0, 'booked', true, auth.uid())
        returning id into v_booking_id;
    end if;
    return jsonb_build_object('booking_id', v_booking_id, 'comp', true, 'waitlisted', false);
  end if;

  -- migration 97 (Swindon test, 4 Oct 2026: "Admins must be able to join the waitlist"). Full: the
  -- comp WAITS, never oversells. A new comp joins the back of the queue; someone already waiting keeps
  -- their place. Either way the place they get is free: every promotion path prices a comp at £0.
  if v_existing.id is not null then
    update bookings set comp = true, comped_by = auth.uid(), price_charged_pennies = 0, taster = false
     where id = v_existing.id and status = 'waitlisted'
    returning id, waitlist_pos into v_booking_id, v_pos;
  else
    select coalesce(max(waitlist_pos), 0) + 1 into v_pos from bookings
     where session_kind = p_session_kind and session_id = p_session_id and status = 'waitlisted';
    insert into bookings(club_id, session_kind, session_id, member_id, price_charged_pennies, status,
                         waitlist_pos, comp, comped_by)
      values (v_club, p_session_kind, p_session_id, p_member_id, 0, 'waitlisted', v_pos, true, auth.uid())
      returning id into v_booking_id;
  end if;

  return jsonb_build_object('booking_id', v_booking_id, 'comp', true, 'waitlisted', true, 'position', v_pos);
end;
$function$;

create or replace function private.promote_waitlist(p_session_kind text, p_session_id uuid)
returns int
language plpgsql security definer set search_path to 'public'
as $$
declare
  v_club uuid; v_played date; v_start text; v_sname text;
  v_capacity int; v_price_m int; v_price_nm int;
  v_host_uid uuid; v_host_name text; v_host_email text;
  v_mode text; v_booked int; v_free int;
  v_promoted int := 0;
  v_id uuid; v_name text; v_wallet int; v_price int; v_taster boolean;
  v_url text;
  v_comp boolean;   -- migration 97
begin
  if p_session_kind = 'social' then
    select club_id, played_on, start_time, coalesce(name, 'Social session'), capacity,
           price_pennies, price_nonmember_pennies, host_user_id, host
      into v_club, v_played, v_start, v_sname, v_capacity, v_price_m, v_price_nm, v_host_uid, v_host_name
      from social_sessions where id = p_session_id for update;
  elsif p_session_kind = 'graded' then
    select club_id, played_on, start_time, 'Graded session', capacity,
           price_pennies, price_nonmember_pennies, host_user_id, host
      into v_club, v_played, v_start, v_sname, v_capacity, v_price_m, v_price_nm, v_host_uid, v_host_name
      from session_plans where id = p_session_id for update;
  else raise exception 'bad_session_kind'; end if;
  if v_club is null then return 0; end if;
  if v_played is null or v_played < current_date then return 0; end if;   -- history is history

  select coalesce(settings->>'booking_mode', 'paid') into v_mode from clubs where id = v_club;

  loop
    select count(*) into v_booked from bookings
      where session_kind = p_session_kind and session_id = p_session_id
        and status in ('booked', 'attended');
    v_free := case when v_capacity is null then 1 else v_capacity - v_booked end;
    exit when v_free <= 0;

    -- next affordable candidate, in queue order
    v_id := null;
    for v_id, v_name, v_wallet, v_comp in   -- migration 97: + v_comp
      select b.member_id, coalesce(bm.display_name, pl.name, bm.email),
             (select coalesce(sum(amount_pennies), 0) from credits_ledger where member_id = b.member_id),
             coalesce(b.comp, false)   -- migration 97
        from bookings b
        join booking_members bm on bm.id = b.member_id
        left join players pl on pl.id = bm.player_id
       where b.session_kind = p_session_kind and b.session_id = p_session_id and b.status = 'waitlisted'
       order by b.waitlist_pos asc
    loop
      v_price := private.price_for_member(v_id, v_price_m, v_price_nm);
      v_taster := false;
      if v_price > 0 and coalesce(private.taster_remaining(v_id, v_club), 0) > 0 then
        v_price := 0; v_taster := true;
      end if;
      if v_comp then v_price := 0; v_taster := false; end if;   -- migration 97: a comp waits free and plays free
      if v_mode <> 'paid' or v_price = 0 or v_wallet >= v_price then
        -- lock, then re-read the wallet under the lock (same order as migration 21:
        -- session row first, member row second)
        perform 1 from booking_members where id = v_id for update;
        select coalesce(sum(amount_pennies), 0) into v_wallet from credits_ledger where member_id = v_id;
        if v_mode = 'paid' and v_price > 0 and v_wallet < v_price then
          v_id := null; continue;
        end if;
        update bookings set status = 'booked', waitlist_pos = null,
               price_charged_pennies = v_price, taster = v_taster
          where session_kind = p_session_kind and session_id = p_session_id
            and member_id = v_id and status = 'waitlisted';
        if v_mode = 'paid' and v_price > 0 then
          insert into credits_ledger(club_id, member_id, amount_pennies, reason, booking_id)
            values (v_club, v_id, -v_price, 'booking',
                    (select id from bookings where session_kind = p_session_kind
                        and session_id = p_session_id and member_id = v_id and status = 'booked' limit 1));
        end if;
        exit;   -- promoted one; outer loop re-counts and continues while spots remain
      end if;
      v_id := null;
    end loop;
    exit when v_id is null;   -- nobody left who can take the spot
    v_promoted := v_promoted + 1;

    perform private.notify_promotion(p_session_kind, p_session_id, v_id, v_price, 'capacity', null);   -- migration 79
  end loop;

  return v_promoted;
end $$;

create or replace function public.cancel_booking(p_session_kind text, p_session_id uuid, p_member_id uuid)
returns jsonb
language plpgsql
security definer
set search_path to 'public'
as $fn$
declare
  v_member_club uuid; v_club uuid; v_bk bookings;
  v_played date; v_start text; v_sname text; v_price int; v_cutoff_hours numeric; v_hours numeric;
  v_price_m int; v_price_nm int; v_promo_price int; v_promo_taster boolean;
  v_refund_now boolean; v_refund_due boolean; v_refund int := 0; v_mode text;
  v_promoted_id uuid; v_promoted_name text; v_promoted_wallet int;
  v_note text; v_url text; v_promote_ok boolean;
  v_host_uid uuid; v_host_name text; v_host_email text; v_canceller text;
  v_promo_comp boolean;   -- migration 97
begin
  select club_id into v_member_club from booking_members
    where id = p_member_id and auth_user_id = auth.uid();
  if v_member_club is null then raise exception 'not_your_member'; end if;

  if p_session_kind = 'social' then
    select played_on, start_time, coalesce(name, 'Social session'), host_user_id, host,
           price_pennies, price_nonmember_pennies
      into v_played, v_start, v_sname, v_host_uid, v_host_name, v_price_m, v_price_nm
      from social_sessions where id = p_session_id for update;
  elsif p_session_kind = 'graded' then
    select played_on, start_time, 'Graded session', host_user_id, host,
           price_pennies, price_nonmember_pennies
      into v_played, v_start, v_sname, v_host_uid, v_host_name, v_price_m, v_price_nm
      from session_plans where id = p_session_id for update;
  else raise exception 'bad_session_kind'; end if;

  perform 1 from booking_members where id = p_member_id for update;

  select * into v_bk from bookings
    where session_kind = p_session_kind and session_id = p_session_id
      and member_id = p_member_id and status in ('booked', 'waitlisted') limit 1;
  if v_bk.id is null then raise exception 'no_booking'; end if;
  v_club := v_bk.club_id;
  select coalesce(settings->>'booking_mode', 'paid') into v_mode from clubs where id = v_club;

  if v_bk.status = 'waitlisted' then
    -- migration 84: record WHEN, as the two admin paths already do
    update bookings set status = 'cancelled', waitlist_pos = null, cancelled_at = now() where id = v_bk.id;
    return jsonb_build_object('refunded', false, 'refund_pence', 0, 'note', 'Left the waitlist.');
  end if;

  select coalesce((settings->>'cancel_cutoff_hours')::numeric, 24) into v_cutoff_hours from clubs where id = v_club;
  v_hours := extract(epoch from (
    ((v_played + coalesce(nullif(v_start, ''), '19:00')::time) at time zone 'Europe/London') - now())) / 3600.0;
  v_refund_now := coalesce(v_hours, 1e9) >= v_cutoff_hours;
  v_price := coalesce(v_bk.price_charged_pennies, 0);

  -- migration 84: record WHEN, as the two admin paths already do
  update bookings set status = 'cancelled', cancelled_at = now() where id = v_bk.id;

  -- THE ONLY CHANGE FROM MIGRATION 48. Everything else is 48 verbatim.
  -- Too close to the start to expect anybody to read an email and travel: release
  -- the spot, promote nobody, charge nobody. v_refund_due below is untouched, so
  -- the canceller correctly gets nothing back -- their spot was not re-sold.
  v_promote_ok := private.promotion_allowed(v_club, v_played, v_start);

  if v_promote_ok then
  for v_promoted_id, v_promoted_name, v_promoted_wallet, v_promo_comp in   -- migration 97: + v_promo_comp
    select b.member_id, coalesce(bm.display_name, pl.name, bm.email),
           (select coalesce(sum(amount_pennies), 0) from credits_ledger where member_id = b.member_id),
           coalesce(b.comp, false)   -- migration 97
      from bookings b
      join booking_members bm on bm.id = b.member_id
      left join players pl on pl.id = bm.player_id
     where b.session_kind = p_session_kind and b.session_id = p_session_id and b.status = 'waitlisted'
     order by b.waitlist_pos asc
  loop
    v_promo_price := private.price_for_member(v_promoted_id, v_price_m, v_price_nm);
    v_promo_taster := false;
    if v_promo_price > 0 and coalesce(private.taster_remaining(v_promoted_id, v_club), 0) > 0 then
      v_promo_price := 0; v_promo_taster := true;
    end if;
    if v_promo_comp then v_promo_price := 0; v_promo_taster := false; end if;   -- migration 97: a comp waits free and plays free
    if v_mode <> 'paid' or v_promo_price = 0 or v_promoted_wallet >= v_promo_price then
      perform 1 from booking_members where id = v_promoted_id for update;
      select coalesce(sum(amount_pennies), 0) into v_promoted_wallet
        from credits_ledger where member_id = v_promoted_id;
      if v_mode = 'paid' and v_promo_price > 0 and v_promoted_wallet < v_promo_price then
        v_promoted_id := null; v_promoted_name := null; continue;
      end if;
      update bookings set status = 'booked', waitlist_pos = null,
             price_charged_pennies = v_promo_price, taster = v_promo_taster
        where session_kind = p_session_kind and session_id = p_session_id
          and member_id = v_promoted_id and status = 'waitlisted';
      if v_mode = 'paid' and v_promo_price > 0 then
        insert into credits_ledger(club_id, member_id, amount_pennies, reason, booking_id)
          values (v_club, v_promoted_id, -v_promo_price, 'booking',
                  (select id from bookings where session_kind = p_session_kind and session_id = p_session_id
                     and member_id = v_promoted_id and status = 'booked' limit 1));
      end if;
      exit;
    end if;
    v_promoted_id := null; v_promoted_name := null;
  end loop;
  end if;

  -- migration 79: one notifier for every promotion path, and it carries the shared key
  if v_promoted_id is not null then
    perform private.notify_promotion(p_session_kind, p_session_id, v_promoted_id, v_promo_price, 'cancelled', p_member_id);
  end if;

  -- Only paid clubs refund. book_spot skips the wallet entirely when the club is
  -- not in paid mode, but the booking still RECORDS price_charged_pennies -- so an
  -- unguarded refund credited money that was never taken, and book-then-cancel
  -- minted wallet credit out of nothing.
  v_refund_due := (v_mode = 'paid') and (v_refund_now or v_promoted_id is not null);
  if v_refund_due and v_price > 0 then
    v_refund := v_price;
    insert into credits_ledger(club_id, member_id, amount_pennies, reason, booking_id)
      values (v_club, p_member_id, v_refund, 'refund', v_bk.id);
  end if;

  v_note := case
    when v_mode <> 'paid' then 'Cancelled — your spot is released. Nothing was charged.'
    when v_price = 0 then 'Free booking cancelled — spot released.'
    when v_refund_now then 'Cancelled before the cancellation cutoff — money returned to your balance.'
    when v_refund_due then 'Within the cutoff, but your spot was re-sold to the waitlist — money returned to your balance.'
    else 'Cancelled within the cancellation cutoff — no refund (no waitlister took the spot).'
  end;

  return jsonb_build_object('refunded', v_refund_due and v_price > 0, 'refund_pence', v_refund,
    'promoted_name', v_promoted_name, 'promotion_held', not v_promote_ok, 'note', v_note);
end; $fn$;

create or replace function public.admin_remove_booking(p_session_kind text, p_session_id uuid, p_member_id uuid)
returns jsonb
language plpgsql
security definer
set search_path to 'public'
as $function$
declare v_club uuid; v_price int; v_price_nm int; v_bk bookings; v_refund int := 0;
        v_played date; v_start text;
        v_promoted_id uuid; v_promoted_name text; v_promoted_bal int;
        v_due int; v_taster boolean; v_rows int;
        v_promo_comp boolean;   -- migration 97
begin
  if p_session_kind = 'social' then
    select club_id, price_pennies, price_nonmember_pennies, played_on, start_time
      into v_club, v_price, v_price_nm, v_played, v_start
      from social_sessions where id = p_session_id for update;   -- migration 79: lock first, as cancel_booking does
  elsif p_session_kind = 'graded' then
    select club_id, price_pennies, price_nonmember_pennies, played_on, start_time
      into v_club, v_price, v_price_nm, v_played, v_start
      from session_plans where id = p_session_id for update;     -- migration 79
  else raise exception 'bad_session_kind'; end if;
  if v_club is null then raise exception 'session_not_found'; end if;
  if not private.is_club_admin(v_club) then raise exception 'not_admin'; end if;
  perform private.require_admin_perm(v_club, 'booking.remove');   -- migration 71

  select * into v_bk from bookings where session_kind = p_session_kind and session_id = p_session_id
     and member_id = p_member_id and status in ('booked', 'waitlisted') limit 1;
  if v_bk.id is null then raise exception 'no_booking'; end if;

  update bookings set status = 'cancelled', cancelled_at = now(), waitlist_pos = null where id = v_bk.id;

  if v_bk.status = 'booked' and coalesce(v_bk.price_charged_pennies, 0) > 0 then
    v_refund := v_bk.price_charged_pennies;
    insert into credits_ledger(club_id, member_id, amount_pennies, reason, booking_id)
      values (v_club, p_member_id, v_refund, 'refund', v_bk.id);
  end if;

  -- THE ONLY BEHAVIOURAL CHANGE. The refund above is untouched -- removing somebody
  -- still gives them their money back. This gates only the PROMOTION, so an admin
  -- removing a no-show at 18:30 no longer books and charges the next person with
  -- half an hour's notice. They can still let somebody in deliberately with
  -- admin_comp_booking, which is the right way round: a person deciding.
  if v_bk.status = 'booked' and private.promotion_allowed(v_club, v_played, v_start) then
    for v_promoted_id, v_promoted_name, v_promoted_bal, v_promo_comp in   -- migration 97: + v_promo_comp
      select b.member_id, coalesce(bm.display_name, pl.name),
             (select coalesce(sum(amount_pennies), 0) from credits_ledger where member_id = b.member_id),
             coalesce(b.comp, false)   -- migration 97
        from bookings b join booking_members bm on bm.id = b.member_id left join players pl on pl.id = bm.player_id
       where b.session_kind = p_session_kind and b.session_id = p_session_id and b.status = 'waitlisted'
       order by b.waitlist_pos asc
    loop
      -- Price THIS person, the same way cancel_booking and book_spot do.
      v_due := private.price_for_member(v_promoted_id, v_price, v_price_nm);
      v_taster := v_due > 0 and coalesce(private.taster_remaining(v_promoted_id, v_club), 0) > 0;
      if v_taster then v_due := 0; end if;
      if v_promo_comp then v_due := 0; v_taster := false; end if;   -- migration 97: a comp waits free and plays free

      if v_due = 0 or v_promoted_bal >= v_due then
        update bookings set status = 'booked', waitlist_pos = null,
               price_charged_pennies = v_due, taster = v_taster
          where session_kind = p_session_kind and session_id = p_session_id
            and member_id = v_promoted_id and status = 'waitlisted';
        get diagnostics v_rows = row_count;                                   -- migration 79
        if v_rows = 0 then v_promoted_id := null; v_promoted_name := null; continue; end if;
        if v_due > 0 then
          insert into credits_ledger(club_id, member_id, amount_pennies, reason, booking_id)
            values (v_club, v_promoted_id, -v_due, 'booking',
                    (select id from bookings where session_kind = p_session_kind and session_id = p_session_id
                       and member_id = v_promoted_id and status = 'booked' limit 1));
        end if;
        exit;
      end if;
      v_promoted_id := null; v_promoted_name := null;
    end loop;
  end if;

  -- migration 79: this path promoted and charged people with no email at all
  if v_promoted_id is not null then
    perform private.notify_promotion(p_session_kind, p_session_id, v_promoted_id, v_due, 'removed', p_member_id);
  end if;

  return jsonb_build_object('removed', true, 'refund_pennies', v_refund, 'promoted_name', v_promoted_name);
end $function$;

create or replace function public.admin_book_member(p_session_kind text, p_session_id uuid, p_member_id uuid)
returns jsonb
language plpgsql security definer set search_path = ''
as $fn$
declare
  v_club uuid; v_capacity int; v_price_m int; v_price_nm int; v_played date;
  v_member_club uuid; v_revoked timestamptz; v_name text;
  v_existing public.bookings;
  v_mode text; v_price int; v_taster boolean := false; v_guardian boolean := false;
  v_booked int; v_balance int; v_booking_id uuid;
begin
  -- Session first, then member: the same lock order as book_spot and cancel_booking.
  if p_session_kind = 'social' then
    select ss.club_id, ss.capacity, ss.price_pennies, ss.price_nonmember_pennies, ss.played_on
      into v_club, v_capacity, v_price_m, v_price_nm, v_played
      from public.social_sessions ss where ss.id = p_session_id for update;
  elsif p_session_kind = 'graded' then
    select sp.club_id, sp.capacity, sp.price_pennies, sp.price_nonmember_pennies, sp.played_on
      into v_club, v_capacity, v_price_m, v_price_nm, v_played
      from public.session_plans sp where sp.id = p_session_id for update;
  else
    raise exception 'bad_session_kind';
  end if;
  if v_club is null then raise exception 'session_not_found'; end if;
  if not private.is_club_admin(v_club) then raise exception 'not_admin'; end if;
  perform private.require_admin_perm(v_club, 'booking.add');
  if v_played is not null and v_played < current_date then raise exception 'session_in_past'; end if;

  select bm.club_id, bm.revoked_at, coalesce(nullif(btrim(bm.display_name), ''), pl.name, bm.email)
    into v_member_club, v_revoked, v_name
    from public.booking_members bm left join public.players pl on pl.id = bm.player_id
   where bm.id = p_member_id;
  if v_member_club is null then raise exception 'member_not_found'; end if;
  if v_member_club <> v_club then raise exception 'wrong_club'; end if;
  if v_revoked is not null then raise exception 'member_access_removed'; end if;
  perform 1 from public.booking_members bm where bm.id = p_member_id for update;

  -- migration 86: an admin may book anyone in, invite-only or not, and doing so puts them on the
  -- session's invite list -- so the list always includes everybody who is actually coming. If the
  -- booking below is refused, this rolls back with it.
  insert into public.session_invites (club_id, session_kind, session_id, player_id, invited_by, notified_at)
  select v_club, p_session_kind, p_session_id, bm.player_id, (select auth.uid()), now()
    from public.booking_members bm
   where bm.id = p_member_id and bm.player_id is not null
     and private.session_invite_only(p_session_kind, p_session_id)
  on conflict do nothing;

  select * into v_existing from public.bookings b
   where b.session_kind = p_session_kind and b.session_id = p_session_id
     and b.member_id = p_member_id and b.status in ('booked', 'waitlisted', 'attended')
   limit 1;
  if v_existing.id is not null and v_existing.status <> 'waitlisted' then raise exception 'already_booked'; end if;

  select count(*) into v_booked from public.bookings b
   where b.session_kind = p_session_kind and b.session_id = p_session_id and b.status in ('booked', 'attended');
  if v_capacity is not null and v_booked >= v_capacity then raise exception 'session_full'; end if;

  -- Price THIS person exactly as book_spot would.
  select coalesce(c.settings->>'booking_mode', 'paid') into v_mode from public.clubs c where c.id = v_club;
  v_price := private.price_for_member(p_member_id, v_price_m, v_price_nm);
  if v_price > 0 and v_mode = 'paid' and coalesce(private.taster_remaining(p_member_id, v_club), 0) > 0 then
    v_price := 0; v_taster := true;
  end if;
  -- migration 97: someone comped onto the waiting list keeps the comp when an admin books them in.
  if coalesce(v_existing.comp, false) then v_price := 0; v_taster := false; end if;
  v_guardian := coalesce((private.minor_info(p_member_id)->>'is_minor')::boolean, false);

  select coalesce(sum(l.amount_pennies), 0) into v_balance from public.credits_ledger l where l.member_id = p_member_id;
  if v_price > 0 and v_mode = 'paid' and v_balance < v_price then
    raise exception 'insufficient_credit:%', v_price - v_balance;
  end if;

  if v_existing.id is not null then
    update public.bookings b
       set status = 'booked', waitlist_pos = null, price_charged_pennies = v_price,
           taster = v_taster, guardian_required = v_guardian
     where b.id = v_existing.id and b.status = 'waitlisted'
    returning b.id into v_booking_id;
    if v_booking_id is null then raise exception 'already_booked'; end if;
  else
    insert into public.bookings (club_id, session_kind, session_id, member_id, price_charged_pennies, status, taster, guardian_required)
    values (v_club, p_session_kind, p_session_id, p_member_id, v_price, 'booked', v_taster, v_guardian)
    returning id into v_booking_id;
  end if;

  if v_price > 0 and v_mode = 'paid' then
    insert into public.credits_ledger (club_id, member_id, amount_pennies, reason, booking_id, created_by, note)
    values (v_club, p_member_id, -v_price, 'booking', v_booking_id, (select auth.uid()), 'Booked in by an admin');
    v_balance := v_balance - v_price;
  end if;

  insert into public.activity (club_id, action, detail)
  values (v_club, 'admin_booked_member',
          coalesce(v_name, 'A member') || ' was booked in by an admin'
          || case when v_price > 0 and v_mode = 'paid'
                  then ' (£' || to_char(v_price / 100.0, 'FM999990.00') || ' from their wallet)' else '' end);

  perform private.notify_promotion(p_session_kind, p_session_id, p_member_id,
                                   case when v_mode = 'paid' then v_price else 0 end, 'admin_booked', null);

  return jsonb_build_object('booking_id', v_booking_id, 'booked', true, 'name', v_name,
    'price_charged', case when v_mode = 'paid' then v_price else 0 end,
    'taster', v_taster, 'guardian_required', v_guardian,
    'from_waitlist', v_existing.id is not null, 'new_balance', v_balance);
end $fn$;

