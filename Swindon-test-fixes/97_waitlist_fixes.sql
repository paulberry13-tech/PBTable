drop function if exists public.comp_admins(text, uuid);
create function public.comp_admins(p_session_kind text, p_session_id uuid)
returns table(member_id uuid, name text, booked boolean, is_comp boolean,
              waitlisted boolean, waitlist_pos integer)
language plpgsql stable security definer
set search_path to 'public'
as $function$
declare v_club uuid;
begin
  if p_session_kind = 'social' then select club_id into v_club from social_sessions where id = p_session_id;
  elsif p_session_kind = 'graded' then select club_id into v_club from session_plans where id = p_session_id;
  else raise exception 'bad_session_kind'; end if;
  if v_club is null then raise exception 'session_not_found'; end if;
  if not private.is_club_admin(v_club) then raise exception 'not_admin'; end if;

  return query
    select bm.id,
           coalesce(nullif(bm.display_name, ''), pl.name, bm.email) as name,
           exists(select 1 from bookings b where b.session_kind = p_session_kind and b.session_id = p_session_id
                    and b.member_id = bm.id and b.status in ('booked','waitlisted')) as booked,
           exists(select 1 from bookings b where b.session_kind = p_session_kind and b.session_id = p_session_id
                    and b.member_id = bm.id and b.status in ('booked','waitlisted') and b.comp) as is_comp,
           -- migration 97: the comp panel shows who is waiting, and where
           exists(select 1 from bookings b where b.session_kind = p_session_kind and b.session_id = p_session_id
                    and b.member_id = bm.id and b.status = 'waitlisted') as waitlisted,
           (select b.waitlist_pos from bookings b where b.session_kind = p_session_kind and b.session_id = p_session_id
                    and b.member_id = bm.id and b.status = 'waitlisted' limit 1) as waitlist_pos
    from booking_members bm
    join club_admins ca on ca.user_id = bm.auth_user_id and ca.club_id = bm.club_id
    left join players pl on pl.id = bm.player_id
    where bm.club_id = v_club
    order by 2;
end;
$function$;

revoke all on function public.comp_admins(text, uuid) from public;
do $grants$
declare g record;
begin
  for g in select role from _m97_grants loop
    execute format('grant execute on function public.comp_admins(text, uuid) to %I', g.role);
  end loop;
end $grants$;
drop table if exists _m97_grants;

