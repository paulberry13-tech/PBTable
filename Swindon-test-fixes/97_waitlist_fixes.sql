--
-- From Swindon's test report (Sharon, Emily, Stephen, run on the live app) and Paul's notes on it:
--
--  1. NUMBERS WITH GAPS. Sharon (#1) left the waiting list and joined again: Emily stayed #2, Sharon
--     became #3, and nobody was #1. waitlist_pos was set once, on joining, and never closed up. Now a
--     trigger closes the gaps whenever anybody leaves the queue -- leaving it, being promoted, being
--     removed, the session being cancelled -- so the queue always reads 1, 2, 3 in the same order.
--     book_spot's "max + 1" for the next joiner is then right without any change to book_spot.
--     Existing queues are closed up once, below.
