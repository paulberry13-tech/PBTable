-- ===========================================================================================
-- 1. The queue closes up whenever someone leaves it
-- ===========================================================================================
-- Renumbers the session's remaining queue 1..n in its current order. Runs after the change, inside
-- the same transaction, and every caller already holds the session row lock -- so two leavers can't
-- interleave. It only writes rows whose number actually changes.
create or replace function private.compact_waitlist()
returns trigger
language plpgsql security definer set search_path = ''
as $fn$
begin
  update public.bookings b
     set waitlist_pos = q.rn
    from (select w.id, row_number() over (order by w.waitlist_pos nulls last, w.created_at, w.id)::int as rn
            from public.bookings w
           where w.session_kind = old.session_kind and w.session_id = old.session_id
             and w.status = 'waitlisted') q
   where b.id = q.id and b.waitlist_pos is distinct from q.rn;
  return null;
end $fn$;
revoke all on function private.compact_waitlist() from public, anon, authenticated;

-- Fires only when a row LEAVES the queue. The renumbering itself keeps status = 'waitlisted', so it
-- never sets these off again.
drop trigger if exists bookings_compact_waitlist on public.bookings;
create trigger bookings_compact_waitlist
  after update of status on public.bookings
  for each row when (old.status = 'waitlisted' and new.status is distinct from 'waitlisted')
  execute function private.compact_waitlist();

drop trigger if exists bookings_compact_waitlist_delete on public.bookings;
create trigger bookings_compact_waitlist_delete
  after delete on public.bookings
  for each row when (old.status = 'waitlisted')
  execute function private.compact_waitlist();

-- Close up every queue that has a gap today. Same order, no gaps.
update public.bookings b
   set waitlist_pos = q.rn
  from (select w.id, row_number() over (partition by w.session_kind, w.session_id
                                        order by w.waitlist_pos nulls last, w.created_at, w.id)::int as rn
          from public.bookings w
         where w.status = 'waitlisted') q
 where b.id = q.id and b.waitlist_pos is distinct from q.rn;

